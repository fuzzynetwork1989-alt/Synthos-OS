"""Mutation Generator - Generate candidate improvements for RSI"""

from typing import Dict, List, Optional, Tuple
from dataclasses import dataclass
from enum import Enum
import structlog

logger = structlog.get_logger(__name__)


class MutationType(Enum):
    """Types of mutations that can be generated"""
    PROMPT_OPTIMIZATION = "prompt_optimization"
    CONFIGURATION_UPDATE = "configuration_update"
    CODE_REFACTORING = "code_refactoring"
    NEW_COMPONENT = "new_component"
    WORKFLOW_RESTRUCTURING = "workflow_restructuring"


@dataclass
class Mutation:
    """Candidate mutation for self-improvement"""
    id: str
    type: MutationType
    description: str
    text: str
    changed_files: List[str]
    diff: str
    expected_improvement: str
    risk_level: str  # "low", "medium", "high"


class MutationGenerator:
    """
    Generate candidate mutations for self-improvement
    
    Generates various types of mutations based on system analysis:
    - Prompt optimization
    - Configuration updates
    - Code refactoring
    - New component generation
    - Workflow restructuring
    """
    
    def __init__(self, config: Dict = None):
        """
        Initialize mutation generator
        
        Args:
            config: Configuration for mutation generation
        """
        self.config = config or self._default_config()
        self.mutation_counter = 0
        
        logger.info("Mutation Generator initialized", config=self.config)
    
    def _default_config(self) -> Dict:
        """Default configuration for mutation generator"""
        return {
            "max_mutations_per_cycle": 5,
            "risk_threshold": "medium",  # Maximum risk level to generate
            "allowed_mutation_types": [
                "prompt_optimization",
                "configuration_update",
                "code_refactoring",
            ],
        }
    
    def generate_mutations(
        self,
        analysis_results: Dict,
        max_mutations: Optional[int] = None
    ) -> List[Mutation]:
        """
        Generate candidate mutations based on analysis results
        
        Args:
            analysis_results: Results from system analysis
            max_mutations: Maximum number of mutations to generate
            
        Returns:
            List of candidate mutations
        """
        max_mutations = max_mutations or self.config["max_mutations_per_cycle"]
        mutations = []
        
        # Generate mutations based on analysis
        mutations.extend(self._generate_prompt_mutations(analysis_results))
        mutations.extend(self._generate_config_mutations(analysis_results))
        mutations.extend(self._generate_refactoring_mutations(analysis_results))
        
        # Filter by risk threshold
        max_risk = self.config["risk_threshold"]
        risk_order = {"low": 0, "medium": 1, "high": 2}
        max_risk_level = risk_order[max_risk]
        
        filtered_mutations = [
            m for m in mutations
            if risk_order[m.risk_level] <= max_risk_level
        ]
        
        # Limit to max mutations
        limited_mutations = filtered_mutations[:max_mutations]
        
        logger.info(
            "Mutations generated",
            total=len(mutations),
            filtered=len(filtered_mutations),
            final=len(limited_mutations)
        )
        
        return limited_mutations
    
    def _generate_prompt_mutations(self, analysis_results: Dict) -> List[Mutation]:
        """Generate prompt optimization mutations"""
        mutations = []
        
        # Example: Generate prompt improvements based on performance bottlenecks
        for bottleneck in analysis_results.get("performance_bottlenecks", []):
            mutation = Mutation(
                id=self._generate_mutation_id(),
                type=MutationType.PROMPT_OPTIMIZATION,
                description=f"Optimize prompt for {bottleneck}",
                text=f"# Prompt optimization for {bottleneck}\n# Generated by RSI system",
                changed_files=["services/cognitive-engine/prompts/"],
                diff=self._generate_placeholder_diff(),
                expected_improvement=f"Improved performance for {bottleneck}",
                risk_level="low"
            )
            mutations.append(mutation)
        
        return mutations
    
    def _generate_config_mutations(self, analysis_results: Dict) -> List[Mutation]:
        """Generate configuration update mutations"""
        mutations = []
        
        # Example: Generate configuration improvements
        for issue in analysis_results.get("code_quality_issues", []):
            mutation = Mutation(
                id=self._generate_mutation_id(),
                type=MutationType.CONFIGURATION_UPDATE,
                description=f"Update configuration for {issue}",
                text=f"# Configuration update for {issue}\n# Generated by RSI system",
                changed_files=["services/config/"],
                diff=self._generate_placeholder_diff(),
                expected_improvement=f"Resolved {issue}",
                risk_level="low"
            )
            mutations.append(mutation)
        
        return mutations
    
    def _generate_refactoring_mutations(self, analysis_results: Dict) -> List[Mutation]:
        """Generate code refactoring mutations"""
        mutations = []
        
        # Example: Generate refactoring improvements
        for opportunity in analysis_results.get("optimization_opportunities", []):
            mutation = Mutation(
                id=self._generate_mutation_id(),
                type=MutationType.CODE_REFACTORING,
                description=f"Refactor code for {opportunity}",
                text=f"# Code refactoring for {opportunity}\n# Generated by RSI system",
                changed_files=["services/cognitive-engine/"],
                diff=self._generate_placeholder_diff(),
                expected_improvement=f"Optimized {opportunity}",
                risk_level="medium"
            )
            mutations.append(mutation)
        
        return mutations
    
    def _generate_mutation_id(self) -> str:
        """Generate unique mutation ID"""
        self.mutation_counter += 1
        return f"mutation_{self.mutation_counter}"
    
    def _generate_placeholder_diff(self) -> str:
        """Generate placeholder diff"""
        return """
--- a/example.py
+++ b/example.py
@@ -1,1 +1,1 @@
-old code
+new code
"""
    
    def validate_mutation(self, mutation: Mutation) -> Tuple[bool, List[str]]:
        """
        Validate a mutation before generation
        
        Args:
            mutation: Mutation to validate
            
        Returns:
            Tuple of (is_valid, list of validation errors)
        """
        errors = []
        
        # Check if mutation type is allowed
        if mutation.type.value not in self.config["allowed_mutation_types"]:
            errors.append(f"Mutation type {mutation.type.value} not allowed")
        
        # Check if changed files are in allowed paths
        allowed_paths = ["services/", "apps/", "packages/"]
        for file_path in mutation.changed_files:
            if not any(allowed in file_path for allowed in allowed_paths):
                errors.append(f"File {file_path} not in allowed paths")
        
        # Check risk level
        risk_order = {"low": 0, "medium": 1, "high": 2}
        max_risk = self.config["risk_threshold"]
        if risk_order[mutation.risk_level] > risk_order[max_risk]:
            errors.append(f"Risk level {mutation.risk_level} exceeds threshold {max_risk}")
        
        is_valid = len(errors) == 0
        
        return is_valid, errors
